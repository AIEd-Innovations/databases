#!/usr/bin/env python3
"""Generate `docs/collections.md` from the schema registry.

`docs/collections.md` is GENERATED. Never hand-edit it: change the schema
module and run this. `tests/test_docs.py` fails when the file on disk does
not match what this script would write, so a forgotten regeneration shows up
as a test failure rather than stale documentation.

    python scripts/gen_docs.py            # write docs/collections.md
    python scripts/gen_docs.py --check    # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from aied_db import schema  # noqa: E402
from aied_db.access import POLICY, Role  # noqa: E402

OUTPUT = ROOT / "docs" / "collections.md"

HEADER = """<!-- GENERATED by scripts/gen_docs.py. Do not edit by hand. -->

# Collections

The `aied` database: {count} collections, each with a `$jsonSchema` validator
and its indexes. Validation level is `moderate` by default — existing
documents are left alone, new and changed ones are checked.

Field tables below are generated from `aied_db/schema/`. The access column of
each collection's policy table is generated from `POLICY` in
`aied_db/access.py`.

| Group | Collections |
| --- | --- |
{groups}
"""


def _type_of(spec: dict) -> str:
    if "enum" in spec:
        return "enum(" + ", ".join(str(choice) for choice in spec["enum"]) + ")"
    bson_type = spec.get("bsonType")
    if bson_type is None:
        return "any"
    if isinstance(bson_type, list):
        return " \\| ".join(bson_type)
    if bson_type == "array":
        items = spec.get("items", {})
        return f"array<{_type_of(items)}>" if items else "array"
    return str(bson_type)


def _constraints(spec: dict) -> str:
    parts = []
    # Draft-4 (MongoDB): exclusiveMinimum/Maximum are booleans that make
    # minimum/maximum strict, so render them as `> 0` rather than separately.
    if "minimum" in spec:
        op = ">" if spec.get("exclusiveMinimum") is True else ">="
        parts.append(f"`{op} {spec['minimum']}`")
    if "maximum" in spec:
        op = "<" if spec.get("exclusiveMaximum") is True else "<="
        parts.append(f"`{op} {spec['maximum']}`")
    for key, label in (
        ("minItems", "minItems"),
        ("maxItems", "maxItems"),
        ("pattern", "pattern"),
    ):
        if key in spec:
            parts.append(f"`{label} {spec[key]}`" if label in (">=", "<=", ">") else f"{label} `{spec[key]}`")
    return ", ".join(parts)


def _escape(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _field_rows(properties: dict, required: set[str], prefix: str = "") -> list[str]:
    rows = []
    for name, spec in properties.items():
        if name == "_id":
            continue
        path = f"{prefix}{name}"
        flag = "yes" if name in required and not prefix else ""
        rows.append(
            "| `{path}` | {type} | {req} | {constraints} | {description} |".format(
                path=path,
                type=_escape(_type_of(spec)),
                req=flag,
                constraints=_constraints(spec) or "",
                description=_escape(spec.get("description", "")),
            )
        )
        # One level of nesting, so embedded documents are visible.
        if not prefix:
            nested = spec.get("properties")
            if nested is None and spec.get("items", {}).get("properties"):
                nested = spec["items"]["properties"]
                path = f"{path}[]"
            if nested:
                rows.extend(
                    _field_rows(nested, set(), prefix=f"{path}.")
                )
    return rows


def render() -> str:
    groups: dict[str, list[str]] = {}
    for name, owner in schema.OWNERS.items():
        groups.setdefault(owner, []).append(name)

    lines = [
        HEADER.format(
            count=len(schema.COLLECTIONS),
            groups="\n".join(
                f"| `{owner}` | {', '.join(f'[{n}](#{n})' for n in sorted(names))} |"
                for owner, names in groups.items()
            ),
        )
    ]

    for owner, names in groups.items():
        lines.append(f"\n## {owner}\n")
        for name in sorted(names):
            spec = schema.COLLECTIONS[name]
            document = spec["schema"]
            required = set(document.get("required", []))

            lines.append(f"\n### {name}\n")
            lines.append("| Field | Type | Required | Constraints | Notes |")
            lines.append("| --- | --- | --- | --- | --- |")
            lines.extend(_field_rows(document.get("properties", {}), required))

            lines.append("\n**Indexes**\n")
            lines.append("| Keys | Unique | Purpose |")
            lines.append("| --- | --- | --- |")
            for keys, unique, why in spec["indexes"]:
                lines.append(
                    f"| `{schema.index_name(keys)}` | {'yes' if unique else ''} | {_escape(why)} |"
                )

            lines.append("\n**Access**\n")
            lines.append("| Role | May | Updatable fields |")
            lines.append("| --- | --- | --- |")
            for role in Role:
                permission = POLICY[name].get(role)
                if permission is None or not permission.ops:
                    continue
                fields = (
                    "all"
                    if permission.fields is None
                    else ", ".join(f"`{f}`" for f in sorted(permission.fields))
                )
                lines.append(
                    f"| `{role.value}` | {', '.join(sorted(permission.ops))} | {fields} |"
                )

    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    args = parser.parse_args()

    content = render()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date — run python scripts/gen_docs.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
